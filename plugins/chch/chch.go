// Плагин chch — инжектор «секретных» страниц. Сам по себе ничего не рисует:
// только читает конфиг chch.json из вшитой папки /rough и для каждого секретного
// кода регистрирует в движке навигацию (AddCheatRoute): набрал код → движок
// открывает страницу.
//
// Страницы при этом — ОБЫЧНЫЕ тайлы в tiles.json со своим html (в tiles/), просто
// не в menu: вкладок не видно, попасть можно только секретным кодом.
//
// Плагин полностью опционален: удалишь импорт chch — движок работает как
// обычно, просто секретных страниц нет.
//
// Формат chch.json (стиль как у тем: сверху заголовок-описание, внутри плоский
// список кодов, без вложенных заголовков):
//
//	{
//	  "title": "chch — секретные страницы",
//	  "description": "Введи код на клавиатуре — откроется скрытая страница.",
//	  "cheats": {
//	    "ps+": "/ps",
//	    "UUDDLRLRba": "/konami"
//	  }
//	}
package chch

import (
	"encoding/json"
	"io/fs"

	"github.com/arctcl/rough"
)

// chchConf — конфиг инжектора: заголовок-описание и плоский список кодов.
type chchConf struct {
	Title       string            `json:"title"`       // заголовок (справочно)
	Description string            `json:"description"` // описание (справочно)
	Cheats      map[string]string `json:"cheats"`      // секретный код → роут страницы
}

func init() {
	// Конфиг читаем после старта движка (в init() вшитой папки ещё нет).
	// OnReady — общий хук движка для плагинов-инжекторов.
	rough.OnReady(load)
}

// load читает chch.json из вшитой папки /rough и регистрирует секретные коды
// как переход на страницу. Нет файла или ошибка — плагин молча бездействует
// (движок работает как обычно).
func load(fsys fs.FS) {
	b, err := fs.ReadFile(fsys, "chch.json")
	if err != nil {
		return
	}
	var c chchConf
	if err := json.Unmarshal(b, &c); err != nil {
		return
	}
	// Для каждого кода — переход на страницу (навигация, как по вкладке).
	for seq, route := range c.Cheats {
		rough.AddCheatRoute(seq, route)
	}
}
