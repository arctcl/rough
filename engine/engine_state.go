package engine

import "sync"

// engineMu — общий мьютекс состояния, к которому могут обращаться ФОНОВЫЕ
// (async) горутины плагинов. Плагин-API (Window, PluginKey, ThemeColor,
// SetVar, VarLine, SwitchTheme) берёт RLock/Lock, а записи в главном цикле —
// Lock. Так async-горутина не читает состояние ядра вразнобой с главным
// циклом → рейсов нет. Экран рисует ТОЛЬКО главный цикл (вне этого мьютекса).
var engineMu sync.RWMutex

// Engine — контейнер состояния движка (рефакторинг глобалов).
//
// Цель: убрать «десятки разбросанных глобалов» и собрать состояние в одну
// структуру. Миграция поэтапная (это первый этап: состояние мыши).
type Engine struct {
	// Состояние мыши (единый обработчик handleMouseEvent).
	mouseX, mouseY int // позиция (для подсветки под курсором; -1 — вне экрана)
	mouseBtn1      bool
	mouseLastX     int // прошлая позиция (для drag/свайпа)
	mouseLastY     int
}

// eng — единый экземпляр состояния движка. Инициализируется на уровне пакета,
// чтобы тесты и код до Run() не ловили nil.
var eng = &Engine{mouseX: -1, mouseY: -1}
